#!/usr/bin/env node
// Regenerates supabase/full_schema_setup.sql by concatenating every migration in order.
//
// README's "1-Click Setup" tells people to paste that file into the Supabase SQL Editor, so a stale copy
// is worse than no copy: it produces a database that looks complete and silently lacks whatever was
// added after it was last generated. It was written by hand once and went stale within days — five
// migrations (auth providers, FCM push, account deletion, OTP delivery, WhatsApp notifications) were
// missing, including the account deletion Apple requires before it will accept the iOS app.
//
//   node scripts/generate-full-schema.mjs
//
// Run it after adding a migration. `npm run lint` fails if the file is out of date.
//
//   node scripts/generate-full-schema.mjs --check   # verify only, exit 1 if stale

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.dirname(fileURLToPath(import.meta.url)) + '/..';
const migrationsDir = path.join(repoRoot, 'supabase', 'migrations');
const outFile = path.join(repoRoot, 'supabase', 'full_schema_setup.sql');
const checkOnly = process.argv.includes('--check');

const files = readdirSync(migrationsDir).filter((name) => name.endsWith('.sql')).sort();

const header = `-- ==============================================================================
-- TIPS BEAUTY — COMPLETE CONSOLIDATED SUPABASE DATABASE SCHEMA
-- This file is GENERATED by scripts/generate-full-schema.mjs from supabase/migrations.
-- Do not edit it by hand: re-run the script after adding a migration.
-- It merges all ${files.length} migrations in sequential order and can be run directly in the
-- Supabase SQL Editor.
-- ==============================================================================

`;

const body = files
    .map((name) => {
        // Strip a UTF-8 BOM: concatenated mid-file it is an invalid token, not invisible whitespace.
        const sql = readFileSync(path.join(migrationsDir, name), 'utf8').replace(/^﻿/, '');
        return `\n\n-- >>>>> Migration: ${name} <<<<<\n\n${sql.trimEnd()}\n`;
    })
    .join('');

const content = header + body.trimStart() + '\n';

if (checkOnly) {
    let current = '';
    try {
        current = readFileSync(outFile, 'utf8').replace(/^﻿/, '');
    } catch {
        console.error('full_schema_setup.sql is missing — run: node scripts/generate-full-schema.mjs');
        process.exit(1);
    }
    if (current !== content) {
        console.error(
            'full_schema_setup.sql is out of date with supabase/migrations.\n' +
            'README tells people to run it as a 1-click setup, so a stale copy ships a database that is\n' +
            'missing migrations. Fix with: node scripts/generate-full-schema.mjs',
        );
        process.exit(1);
    }
    console.log(`full_schema_setup.sql is up to date (${files.length} migrations).`);
} else {
    writeFileSync(outFile, content, 'utf8');
    console.log(`full_schema_setup.sql regenerated from ${files.length} migrations.`);
}
